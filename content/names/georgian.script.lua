-- Picked at random per street, so most streets are ქუჩა (street).
local streetTypes = {
  "ქუჩა", "ქუჩა", "ქუჩა", "ქუჩა", "ქუჩა", "გამზირი", "შესახვევი",
}

local function pick(list)
  return list[math.random(#list)]
end

local function shuffle(list)
  for i = #list, 2, -1 do
    local j = math.random(i)
    list[i], list[j] = list[j], list[i]
  end
  return list
end

-- Takes `num` names in random order, using up `main` before touching `extra`.
-- num = -1 means all.
local function take(main, extra, num)
  local names = shuffle(main)
  for _, name in ipairs(shuffle(extra)) do
    names[#names + 1] = name
  end
  if num == -1 then
    return names
  end
  local result = {}
  for i = 1, math.min(num, #names) do
    result[#result + 1] = names[i]
  end
  return result
end

local function townNames(num)
  local main, extra = {}, {}
  for _, town in ipairs(towns) do
    main[#main + 1] = town
    for _, prefix in ipairs(townPrefixes) do
      extra[#extra + 1] = prefix .. town
    end
  end
  return take(main, extra, num)
end

-- "რუსთაველის ქუჩა". Extra: numbered lanes, "რუსთაველის მე-2 შესახვევი".
local function streetNames(num)
  local main, extra = {}, {}
  for _, base in ipairs(streetBases) do
    main[#main + 1] = base .. " " .. pick(streetTypes)
    for n = 2, 5 do
      extra[#extra + 1] = base .. " მე-" .. n .. " შესახვევი"
    end
  end
  return take(main, extra, num)
end

